import { cpSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";
import { afterAll, describe, expect, it } from "vitest";
import { checkProject } from "../src/index.js";
import type { CheckCounts } from "../src/types.js";

// The README quotes four `check` runs and one `--json` body. Every count in
// them - 3 high here, 1 low there - is a claim about what the fixture on disk
// produces, and the fixtures are generated by scripts that nobody re-reads.
// A rule tweak or a new demo line moves the numbers and leaves the README
// quoting a run that no longer happens. These tests rebuild each fixture from
// its generator and compare the README against the real result.

const root = fileURLToPath(new URL("..", import.meta.url));
const readme = readFileSync(join(root, "README.md"), "utf8");
const dirs: string[] = [];

afterAll(() => {
  for (const dir of dirs) rmSync(dir, { recursive: true, force: true });
});

function scratch(prefix: string): string {
  const dir = mkdtempSync(join(tmpdir(), prefix));
  dirs.push(dir);
  return dir;
}

/** The summary line `check` prints, exactly as the report renders it. */
function summary(counts: CheckCounts): string {
  return `${counts.high} high, ${counts.medium} medium, ${counts.low} low`;
}

/**
 * Asserts the README still contains a line stating these counts and this exit
 * code. Anchored on the whole line so a changed number cannot match by prefix.
 */
function expectQuoted(counts: CheckCounts, exitCode: number): void {
  const line = `${summary(counts)}  -> exit ${exitCode}`;
  expect(readme).toContain(line);
}

function writeTree(dir: string, files: Record<string, string>): string {
  for (const [relative, body] of Object.entries(files)) {
    const target = join(dir, relative);
    mkdirSync(join(target, ".."), { recursive: true });
    writeFileSync(target, body);
  }
  return dir;
}

/** Copies the fixtures and their generators out of the repo before running them. */
function generateExamples(): string {
  const dir = scratch("envpulse-readme-");
  cpSync(join(root, "examples"), join(dir, "examples"), { recursive: true });
  cpSync(join(root, "scripts"), join(dir, "scripts"), { recursive: true });
  for (const script of ["make-demo-app.mjs", "make-leaky-fixture.mjs"]) {
    const run = spawnSync(process.execPath, [join(dir, "scripts", script)], { encoding: "utf8" });
    expect(run.status).toBe(0);
  }
  return dir;
}

describe("README demo transcripts", () => {
  it("quotes the counts the demo-app fixture really produces", async () => {
    const dir = generateExamples();
    const report = await checkProject({ cwd: join(dir, "examples", "demo-app") });
    expectQuoted(report.counts, report.exitCode);
    // The --json block in the README carries the same three numbers.
    expect(readme).toContain(`"high": ${report.counts.high},`);
    expect(readme).toContain(`"medium": ${report.counts.medium},`);
    expect(readme).toContain(`"low": ${report.counts.low}`);
  });

  it("quotes the counts the leaky fixture really produces", async () => {
    const dir = generateExamples();
    const report = await checkProject({ cwd: join(dir, "examples", "leaky") });
    expectQuoted(report.counts, report.exitCode);
  });

  it("quotes the swallowed-assignment run", async () => {
    // The `=` is missing on line 2: the variable vanishes, which is a DRIFT
    // and an INVALID, and neither is high - so the run exits 0 on purpose.
    const dir = writeTree(scratch("envpulse-noequals-"), {
      ".env": "GOOD=1\nDATABASE_URL postgres://x\nSECRET_KEY=abc\n",
      ".env.example": "GOOD=hello\nDATABASE_URL=postgres://localhost/db\nSECRET_KEY=changeme\n",
      "src/index.js": [
        "const good = process.env.GOOD;",
        "const url = process.env.DATABASE_URL;",
        "const key = process.env.SECRET_KEY;",
        "",
      ].join("\n"),
    });
    const report = await checkProject({ cwd: dir });
    expectQuoted(report.counts, report.exitCode);
  });

  it("quotes the run that falls back to the .env as its template", async () => {
    const dir = writeTree(scratch("envpulse-dotenv-only-"), {
      ".env": "API_URL=https://api.example.com\nDEBUG=true\n",
      "index.js": "const api = process.env.API_URL;\n",
    });
    const report = await checkProject({ cwd: dir });
    expectQuoted(report.counts, report.exitCode);
  });
});
